/**
 * 承認の通知の時点(WP-P4-APR-019 §6.1 / ADR-0023 §8)。
 *
 * 期限前の通知は「期限まで24時間以内」に1回だけ送る。
 * 閾値を定期処理とテストで別々に持つと、
 * 「画面は期限が近いと言うのに通知が来ない」という食い違いが起きる。
 * 値はここ1か所だけに置き、呼び出し側はこの定数を使う。
 */
export const APPROVAL_NOTICE_LEAD_HOURS = 24;

/**
 * 承認の定期処理の間隔(WP-P4-APR-019 §6.3)。
 *
 * 10分。期限前の24時間・期限の72時間に対して十分細かく、かつ
 * 1周で全組織を回しても10分以内に収まる粒度である。
 * 起動時に1周するため、落ちていた間の分も次の起動で処理できる。
 */
export const APPROVAL_NOTICE_SWEEP_INTERVAL_MS = 10 * 60 * 1000;
